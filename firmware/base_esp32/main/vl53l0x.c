// VL53L0X, ported from pololu/vl53l0x-arduino (MIT). Only what a downward cliff sensor needs: default 33 ms budget,
// back-to-back continuous mode, non-blocking reads.
#include "vl53l0x.h"

#include "esp_timer.h"
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"

#define TMO_MS 20

static bool wr(vl53l0x_t* s, uint8_t reg, uint8_t v) {
  uint8_t b[2] = {reg, v};
  return i2c_master_transmit(s->dev, b, 2, TMO_MS) == ESP_OK;
}
static uint8_t rd(vl53l0x_t* s, uint8_t reg) {
  uint8_t v = 0;
  i2c_master_transmit_receive(s->dev, &reg, 1, &v, 1, TMO_MS);
  return v;
}
static bool rd_n(vl53l0x_t* s, uint8_t reg, uint8_t* out, size_t n) {
  return i2c_master_transmit_receive(s->dev, &reg, 1, out, n, TMO_MS) == ESP_OK;
}
static bool wait_nz(vl53l0x_t* s, uint8_t reg, uint8_t mask, bool want_nonzero) {
  int64_t end = esp_timer_get_time() + 500000;
  while (((rd(s, reg) & mask) != 0) != want_nonzero) {
    if (esp_timer_get_time() > end) return false;
    vTaskDelay(1);
  }
  return true;
}

